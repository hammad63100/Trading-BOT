# ---------------------------------------------------------------------------
# Confidence Boosters
# ---------------------------------------------------------------------------

def _apply_confidence_boosters(
    direction: str,
    base_conf: float,
    last: dict,
    prev: dict
) -> tuple[float, list]:
    """
    Adds up to ~0.30 confidence based on additional confirming factors.
    """
    bonuses = []

    # Booster 1: Active trading session (+0.08)
    if last.get("in_session") == 1:
        base_conf += 0.08
        bonuses.append("active_session(+0.08)")

    # Booster 2: RSI Divergence (+0.07)
    if direction == "LONG" and last.get("rsi_bull_div") == 1:
        base_conf += 0.07
        bonuses.append("rsi_bull_div(+0.07)")
    elif direction == "SHORT" and last.get("rsi_bear_div") == 1:
        base_conf += 0.07
        bonuses.append("rsi_bear_div(+0.07)")

    # Booster 3: Stochastic agrees with direction (+0.06)
    stoch_k = last.get("stoch_k")
    stoch_d = last.get("stoch_d")
    if stoch_k is not None and stoch_d is not None:
        if direction == "LONG" and stoch_k > stoch_d and stoch_k < 80:
            base_conf += 0.06
            bonuses.append("stoch_bull(+0.06)")
        elif direction == "SHORT" and stoch_k < stoch_d and stoch_k > 20:
            base_conf += 0.06
            bonuses.append("stoch_bear(+0.06)")

    # Booster 4: Strong directional candle body (+0.05)
    body_ratio = last.get("body_ratio")
    close = last.get("close")
    open_ = last.get("open")
    if body_ratio is not None and close is not None and open_ is not None:
        if body_ratio > 0.5:
            candle_bullish = close > open_
            if (direction == "LONG" and candle_bullish) or (direction == "SHORT" and not candle_bullish):
                base_conf += 0.05
                bonuses.append(f"strong_candle(+0.05, ratio={body_ratio:.2f})")

    # Booster 5: EMA20 short-term alignment (+0.05)
    ema20 = last.get("ema20")
    ema50 = last.get("ema50")
    if ema20 is not None and ema50 is not None:
        if direction == "LONG" and ema20 > ema50:
            base_conf += 0.05
            bonuses.append("ema20_bull(+0.05)")
        elif direction == "SHORT" and ema20 < ema50:
            base_conf += 0.05
            bonuses.append("ema20_bear(+0.05)")

    return min(base_conf, 1.0), bonuses


# ---------------------------------------------------------------------------
# Main Signal Generator
# ---------------------------------------------------------------------------

def generate_signal(df: pd.DataFrame, ml_model=None) -> Signal:
    """
    Runs all five strategies and selects the highest-confidence signal.
    Applies ADX filter, MTF check, confidence boosters, and gates against MIN_SIGNAL_CONFIDENCE.

    Args:
        df:       DataFrame with computed indicators.
        ml_model: Optional ML model.

    Returns:
        Signal object.
    """
    from config.settings import MIN_SIGNAL_CONFIDENCE, ADX_MIN_TREND_STRENGTH, SYMBOL

    if len(df) < 25:
        return Signal("FLAT", 0.0, "Insufficient data", strategy="none")

    last = {c: _safe(df, c, -1) for c in df.columns}
    prev = {c: _safe(df, c, -2) for c in df.columns}

    required = ["close", "ema50", "ema200", "rsi14", "macd_hist", "atr14"]
    for col in required:
        if last.get(col) is None:
            return Signal("FLAT", 0.0, f"Missing indicator: {col}", strategy="none")

    # -------------------------------------------------------------------
    # Filter 1: ADX Trend Strength Filter
    # -------------------------------------------------------------------
    adx_val = last.get("adx", 0.0) or 0.0
    if adx_val < ADX_MIN_TREND_STRENGTH:
        log.debug("Signal suppressed | ADX %.1f < min %.1f (ranging market)",
                  adx_val, ADX_MIN_TREND_STRENGTH)
        return Signal(
            direction="FLAT",
            confidence=round(adx_val / 100.0, 4),
            reason=f"ADX low ({adx_val:.1f} < {ADX_MIN_TREND_STRENGTH}) — market is choppy",
            strategy="none"
        )

    # -------------------------------------------------------------------
    # Run all five strategies
    # -------------------------------------------------------------------
    strategies = [
        _strategy_trend_momentum(last, prev),
        _strategy_breakout(last, prev),
        _strategy_rsi_reversal(last, prev),
        _strategy_vwap_momentum(last, prev),
        _strategy_structure_ichimoku(last, prev),
    ]

    active = [(d, c, meta) for d, c, meta in strategies if d != "FLAT"]

    if not active:
        best_conf = max(c for _, c, _ in strategies)
        return Signal(
            direction="FLAT",
            confidence=round(best_conf, 4),
            reason="No strategy reached threshold",
            strategy="none",
            votes_detail={"strategies": [m.get("strategy", "?") for _, _, m in strategies]},
        )

    # Pick the highest confidence signal among active strategies
    direction, base_conf, meta = max(active, key=lambda x: x[1])

    # -------------------------------------------------------------------
    # Filter 2: MTF Check Integration
    # -------------------------------------------------------------------
    try:
        from core.mtf_filter import check_mtf_alignment
        mtf_ok, mtf_reason = check_mtf_alignment(SYMBOL, direction)
        if not mtf_ok:
            return Signal(
                direction="FLAT",
                confidence=round(base_conf, 4),
                reason=mtf_reason,
                strategy=meta.get("strategy", "unknown")
            )
    except Exception as e:
        log.warning("MTF check failed in signal generator: %s", e)

    # -------------------------------------------------------------------
    # Optional ML layer (blends 40% ML, 60% rule)
    # -------------------------------------------------------------------
    if ml_model is not None:
        try:
            from ml.features import extract_feature_vector
            features = extract_feature_vector(df)
            ml_prob_up = ml_model.predict_proba([features])[0][1]
            blended = 0.6 * base_conf + 0.4 * ml_prob_up
            log.debug("ML blend | rule=%.3f, ml=%.3f, blended=%.3f", base_conf, ml_prob_up, blended)
            base_conf = blended
        except Exception as e:
            log.warning("ML prediction failed, using rule-only: %s", e)

    # -------------------------------------------------------------------
    # Apply confidence boosters
    # -------------------------------------------------------------------
    final_conf, bonuses = _apply_confidence_boosters(direction, base_conf, last, prev)

    # -------------------------------------------------------------------
    # Gate against minimum confidence (0.65)
    # -------------------------------------------------------------------
    strategy_name = meta.get("strategy", "unknown")

    if final_conf < MIN_SIGNAL_CONFIDENCE:
        log.debug(
            "Signal suppressed | Dir: %s | Conf: %.3f < min %.3f | Strategy: %s | Bonuses: %s",
            direction, final_conf, MIN_SIGNAL_CONFIDENCE, strategy_name, bonuses
        )
        return Signal(
            direction="FLAT",
            confidence=round(final_conf, 4),
            reason=f"{strategy_name} signal below min confidence ({final_conf:.2f} < {MIN_SIGNAL_CONFIDENCE})",
            strategy=strategy_name,
            votes_detail=meta.get("votes", {}),
        )

    bonus_str = " | ".join(bonuses) if bonuses else "none"
    reason = f"{strategy_name} | conf={final_conf:.2f} | boosters=[{bonus_str}]"

    icon = "📈" if direction == "LONG" else "📉"
    log.info(
        "%s %s signal | Strategy: %s | Confidence: %.3f | ADX: %.1f | "
        "RSI: %.1f | MACD-H: %.4f | ATR: %.2f | VWAP: %.2f",
        icon, direction, strategy_name, final_conf, adx_val,
        last.get("rsi14") or 0,
        last.get("macd_hist") or 0,
        last.get("atr14") or 0,
        last.get("vwap") or 0,
    )
    if bonuses:
        log.info("   Confidence boosters: %s", bonus_str)

    return Signal(
        direction=direction,
        confidence=round(final_conf, 4),
        reason=reason,
        strategy=strategy_name,
        votes_detail={**meta.get("votes", {}), "boosters": bonuses},
    )
