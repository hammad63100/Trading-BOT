# Strategy 3 — RSI Mean Reversion (tightened thresholds)
# ---------------------------------------------------------------------------

def _strategy_rsi_reversal(last, prev) -> tuple[str, float, dict]:
    """
    Logic:
      LONG  — EMA200 trend is up + RSI < 35 & turning up + MACD hist bullish cross
      SHORT — EMA200 trend is down + RSI > 65 & turning down + MACD hist bearish cross
    """
    from config.settings import RSI_OVERSOLD, RSI_OVERBOUGHT

    result = {"strategy": "rsi_reversal", "votes": {}}

    close    = last.get("close")
    ema200   = last.get("ema200")
    rsi      = last.get("rsi14")
    rsi_prev = prev.get("rsi14")
    mh       = last.get("macd_hist")
    mh_prev  = prev.get("macd_hist")

    if any(v is None for v in [close, ema200, rsi, rsi_prev, mh, mh_prev]):
        return "FLAT", 0.0, result

    long_votes = {
        "price_above_ema200":         close > ema200,
        "rsi_oversold":               rsi < RSI_OVERSOLD,
        "rsi_turning_up":             rsi > rsi_prev,
        "macd_hist_bullish_cross":    mh > 0 and mh_prev <= 0,
    }

    short_votes = {
        "price_below_ema200":         close < ema200,
        "rsi_overbought":             rsi > RSI_OVERBOUGHT,
        "rsi_turning_down":           rsi < rsi_prev,
        "macd_hist_bearish_cross":    mh < 0 and mh_prev >= 0,
    }

    long_count  = sum(long_votes.values())
    short_count = sum(short_votes.values())

    if long_count >= 3 and long_count > short_count:
        conf = long_count / 4.0
        result["votes"] = long_votes
        return "LONG", conf, result

    if short_count >= 3 and short_count > long_count:
        conf = short_count / 4.0
        result["votes"] = short_votes
        return "SHORT", conf, result

    return "FLAT", 0.0, {**result, "votes": {"long": long_votes, "short": short_votes}}


