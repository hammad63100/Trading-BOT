"""
Advanced Signal Generation Engine (v2.0)
=========================================
Professional multi-strategy confluence logic for XAU/USD.

Five complementary strategies run in parallel:

  Strategy 1 — TREND MOMENTUM (primary)
    EMA alignment + price pulls back to EMA50 + RSI in momentum zone + MACD hist positive/rising.

  Strategy 2 — BREAKOUT / MOMENTUM
    Close breaks 20-bar high/low + ATR expanding + RSI confirming + MACD positive.

  Strategy 3 — RSI MEAN REVERSION (tightened 35/65 thresholds)
    RSI turning from oversold/overbought + MACD histogram flip + EMA200 trend.

  Strategy 4 — VWAP & VOLUME MOMENTUM (Institutional)
    Price cross above/below VWAP + high relative volume (>1.2x avg) + MACD direction.

  Strategy 5 — MARKET STRUCTURE & ICHIMOKU CONFLUENCE
    Uptrend/downtrend market structure (HH/HL or LH/LL) + price above/below Ichimoku Cloud + RSI.

Confidence Boosters:
  +0.08 — Active London/NY session
  +0.07 — RSI Divergence detected in direction
  +0.06 — Stochastic confirms direction
  +0.05 — Candle body ratio > 0.5 (strong directional close)
  +0.05 — EMA20 aligns with trade direction

Filters:
  - ADX Trend Strength Filter: ADX must be >= ADX_MIN_TREND_STRENGTH (default 20)
  - MTF Filter Check: Multi-timeframe trend alignment (H1/H4)
  - Min Signal Confidence: 0.65 (raised from 0.55 for higher quality)

Ref: Blueprint Section 5 (extended v2)
"""

import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional

import pandas as pd

log = logging.getLogger("gold_bot.signals")


@dataclass
class Signal:
    """Represents a trading signal generated by the multi-strategy confluence engine."""
    direction:    str    # "LONG", "SHORT", or "FLAT"
    confidence:   float  # 0.0 – 1.0
    reason:       str    # Human-readable explanation
    strategy:     str    = "none"   # Which strategy fired
    timestamp:    str    = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    votes_detail: dict   = field(default_factory=dict)


# ---------------------------------------------------------------------------
# Helper utilities
# ---------------------------------------------------------------------------

def _safe(df: pd.DataFrame, col: str, row: int = -1):
    """Return df[col].iloc[row] or None if missing/NaN."""
    if col not in df.columns:
        return None
    val = df[col].iloc[row]
    return None if pd.isna(val) else val


# ---------------------------------------------------------------------------
# Strategy 1 — Trend Momentum (EMA alignment + pullback to EMA50)
# ---------------------------------------------------------------------------

def _strategy_trend_momentum(last, prev) -> tuple[str, float, dict]:
    """
    Logic:
      LONG  — EMA50 > EMA200 (uptrend) AND price near/below EMA50 (pullback)
              AND RSI 45-70 (momentum zone, not overbought)
              AND MACD histogram positive AND rising

      SHORT — EMA50 < EMA200 (downtrend) AND price near/above EMA50 (pullback)
              AND RSI 30-55 (momentum zone, not oversold)
              AND MACD histogram negative AND falling
    """
    result = {"strategy": "trend_momentum", "votes": {}}

    ema50  = last.get("ema50")
    ema200 = last.get("ema200")
    close  = last.get("close")
    rsi    = last.get("rsi14")
    mh     = last.get("macd_hist")
    mhs    = last.get("macd_hist_slope")

    if any(v is None for v in [ema50, ema200, close, rsi, mh, mhs]):
        return "FLAT", 0.0, result

    trend_up   = ema50 > ema200
    trend_down = ema50 < ema200

    ema50_distance_pct = (close - ema50) / ema50
    near_ema50_long  = -0.003 <= ema50_distance_pct <= 0.005
    near_ema50_short = -0.005 <= ema50_distance_pct <= 0.003

    long_votes = {
        "uptrend_ema50_gt_ema200":    trend_up,
        "pullback_to_ema50":          near_ema50_long,
        "rsi_momentum_zone":          45 <= rsi <= 70,
        "macd_hist_positive":         mh > 0,
        "macd_hist_rising":           mhs > 0,
    }

    short_votes = {
        "downtrend_ema50_lt_ema200":  trend_down,
        "pullback_to_ema50":          near_ema50_short,
        "rsi_momentum_zone":          30 <= rsi <= 55,
        "macd_hist_negative":         mh < 0,
        "macd_hist_falling":          mhs < 0,
    }

    long_count  = sum(long_votes.values())
    short_count = sum(short_votes.values())

    if long_count >= 4 and long_count > short_count:
        conf = long_count / 5.0
        result["votes"] = long_votes
        return "LONG", conf, result

    if short_count >= 4 and short_count > long_count:
        conf = short_count / 5.0
        result["votes"] = short_votes
        return "SHORT", conf, result

    return "FLAT", 0.0, {**result, "votes": {"long": long_votes, "short": short_votes}}


# ---------------------------------------------------------------------------
# Strategy 2 — Breakout / Momentum
# ---------------------------------------------------------------------------

def _strategy_breakout(last, prev) -> tuple[str, float, dict]:
    """
    Logic:
      LONG  — Close breaks above rolling 20-bar high + RSI > 52 + MACD hist > 0 + ATR expanding
      SHORT — Close breaks below rolling 20-bar low + RSI < 48 + MACD hist < 0 + ATR expanding
    """
    result = {"strategy": "breakout", "votes": {}}

    close     = last.get("close")
    rh20      = last.get("roll_high20")
    rl20      = last.get("roll_low20")
    rsi       = last.get("rsi14")
    mh        = last.get("macd_hist")
    atr       = last.get("atr14")
    atr_prev  = prev.get("atr14")

    if any(v is None for v in [close, rh20, rl20, rsi, mh, atr, atr_prev]):
        return "FLAT", 0.0, result

    atr_expanding = atr > atr_prev * 0.98

    long_votes = {
        "price_breaks_20bar_high":  close > rh20,
        "rsi_confirming_bullish":   rsi > 52,
        "macd_hist_positive":       mh > 0,
        "atr_expanding":            atr_expanding,
    }

    short_votes = {
        "price_breaks_20bar_low":   close < rl20,
        "rsi_confirming_bearish":   rsi < 48,
        "macd_hist_negative":       mh < 0,
        "atr_expanding":            atr_expanding,
    }

    long_count  = sum(long_votes.values())
    short_count = sum(short_votes.values())

    if long_count >= 4 and long_count > short_count:
        conf = long_count / 4.0
        result["votes"] = long_votes
        return "LONG", conf, result

    if short_count >= 4 and short_count > long_count:
        conf = short_count / 4.0
        result["votes"] = short_votes
        return "SHORT", conf, result

    return "FLAT", 0.0, {**result, "votes": {"long": long_votes, "short": short_votes}}


